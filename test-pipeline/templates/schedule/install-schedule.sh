#!/usr/bin/env bash
# Register (or remove, or report on) one cron entry PER ENVIRONMENT.
#
#   ./install-schedule.sh              # install for every environment in the config
#   ./install-schedule.sh --status     # show the current entries
#   ./install-schedule.sh --remove     # remove them all
#   ./install-schedule.sh --only qc2   # act on one environment
#
# Entries are written between marker lines so this script can rewrite its own block without
# disturbing anything else in the user's crontab. Editing a crontab in place is otherwise an easy
# way to destroy someone's unrelated jobs.
set -euo pipefail

CONFIG="pipeline.config.json"
MODE="install"
ONLY=""

while [ $# -gt 0 ]; do
  case "$1" in
    --config) CONFIG="$2"; shift 2 ;;
    --status) MODE="status"; shift ;;
    --remove) MODE="remove"; shift ;;
    --only)   ONLY="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
cd "$REPO_ROOT"

command -v node >/dev/null 2>&1 || { echo "node is required to read the config" >&2; exit 1; }
[ -f "$CONFIG" ] || { echo "no config at $CONFIG" >&2; exit 1; }

q() { node -e "const c=require('./$CONFIG');process.stdout.write(String($1))"; }

PIPELINE_DIR="$(q 'c.pipelineDir')"
PREFIX="$(q 'c.taskPrefix||"test-pipeline"')"
START_HOUR="$(q 'c.schedule.startHour')"
END_HOUR="$(q 'c.schedule.endHour')"
START_MIN="$(q 'c.schedule.startMinute')"
STAGGER="$(q 'c.schedule.staggerMinutes||0')"
EVERY="$(q 'c.schedule.everyHours||1')"
DAYS="$(q 'c.schedule.days.map(d=>({sunday:0,monday:1,tuesday:2,wednesday:3,thursday:4,friday:5,saturday:6})[d.toLowerCase()]).join(",")')"
ENVS="$(q 'c.environments.filter(e=>e.enabled!==false).map(e=>e.name).join(" ")')"

RUNNER="$REPO_ROOT/$PIPELINE_DIR/runner/run-cycle.sh"
BEGIN="# BEGIN $PREFIX"
END="# END $PREFIX"

current_crontab() { crontab -l 2>/dev/null || true; }
without_block() { current_crontab | sed "/^$BEGIN\$/,/^$END\$/d"; }

if [ "$MODE" = "status" ]; then
  if current_crontab | grep -q "^$BEGIN\$"; then
    current_crontab | sed -n "/^$BEGIN\$/,/^$END\$/p"
  else
    echo "no $PREFIX entries installed"
  fi
  exit 0
fi

if [ "$MODE" = "remove" ]; then
  without_block | crontab -
  echo "[schedule] removed $PREFIX entries"
  exit 0
fi

# cron has no native jitter, so the runner sleeps a random 0..jitter minutes before starting. A
# fixed start makes platform problems unreadable: you cannot tell "the environment is broken" from
# "the environment is busy with everything else scheduled on the hour".
JITTER="$(q 'c.schedule.jitterMinutes||0')"

{
  without_block
  echo "$BEGIN"
  echo "# Generated by install-schedule.sh - edit pipeline.config.json and re-run, do not hand-edit."
  idx=0
  for e in $ENVS; do
    if [ -n "$ONLY" ] && [ "$e" != "$ONLY" ]; then continue; fi
    minute=$(( (START_MIN + idx * STAGGER) % 60 ))
    hour_bump=$(( (START_MIN + idx * STAGGER) / 60 ))
    from=$(( START_HOUR + hour_bump ))
    echo "$minute $from-$END_HOUR/$EVERY * * $DAYS cd $REPO_ROOT && JITTER_MINUTES=$JITTER $RUNNER --environment $e --config $CONFIG >> $REPO_ROOT/$(q 'c.runsDir')/cron.log 2>&1"
    idx=$(( idx + 1 ))
  done
  echo "$END"
} | crontab -

echo "[schedule] installed. Check with: ./install-schedule.sh --status"
